export const glyphs = new Map();
for (const [character, drawing] of Object.entries(drawings)) {
  let rows = drawing.split("/");
  const columns = rows[0].length;
  assert.ok(rows.every(row => row.length === columns && /^[01]+$/.test(row)));
  const ink = [...Array(columns).keys()].filter(x => rows.some(row => row[x] === "1"));
  rows = rows.map(row => row.slice(ink[0], ink[ink.length - 1] + 1));
  let bottom = rows.length;
  while (bottom && !rows[bottom - 1].includes("1")) bottom--;
  glyphs.set(character, { rows, width: rows[0].length, bottom });
}
glyphs.set(" ", { rows: [], width: 3, bottom: 0 });

// Round the actual cell edge, instead of reserving a phantom extra pixel.
// The ink shapes are unchanged; every pair still has at least one blank pixel.
export function measure(value, capHeight = 9, tracking = 1) {
  assert.ok(capHeight >= 7 && tracking >= 1);
  const unit = capHeight / 7;
  let width = 0;
  let height = 0;
  const slots = [];
  for (const character of value) {
    const glyph = glyphs.get(character);
    assert.ok(glyph, `Unsupported glyph: ${JSON.stringify(character)}`);
    const extent = Math.round(glyph.width * unit);
    slots.push({ glyph, character, x: width, width: extent });
    width += extent + tracking;
    height = Math.max(height, Math.round(glyph.bottom * unit));
  }
  for (let i = 1; i < slots.length; i++) {
    assert.ok(slots[i].x >= slots[i - 1].x + slots[i - 1].width + 1);
  }
  return { slots, unit, width: width ? width - tracking : 0, height };
}

export function wrap(value, width, capHeight = 9, tracking = 1) {
  assert.ok(value && !/\s{2,}|^\s|\s$/.test(value), "Unexpected text whitespace");
  const lines = [];
  let line = "";
  for (const word of value.split(" ")) {
    assert.ok(measure(word, capHeight, tracking).width <= width, `Word too wide: ${word}`);
    const candidate = line ? `${line} ${word}` : word;
    if (measure(candidate, capHeight, tracking).width <= width) line = candidate;
    else { lines.push(line); line = word; }
  }
  lines.push(line);
  assert.equal(lines.join(" "), value, "Wrapping must preserve every word");
  return lines;
}

export function paragraphMetrics(value, width, capHeight = 9, leading = 11.5) {
  const lines = wrap(value, width, capHeight);
  const height = Math.max(...lines.map((line, i) => Math.round(i * leading) + measure(line, capHeight).height));
  return { lines, height };
}
